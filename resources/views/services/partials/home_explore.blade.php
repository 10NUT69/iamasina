<script>
    (() => {
        const tabList = document.getElementById('home-explore-tabs');

        function selectTab(tab) {
            const selectedTab = tabList.querySelector('[aria-selected="true"]');
            if (tab === selectedTab) return;

            selectedTab.setAttribute('aria-selected', 'false');
            selectedTab.tabIndex = -1;
            document.getElementById(selectedTab.getAttribute('aria-controls')).hidden = true;

            tab.setAttribute('aria-selected', 'true');
            tab.tabIndex = 0;
            document.getElementById(tab.getAttribute('aria-controls')).hidden = false;
        }

        tabList.addEventListener('click', (event) => {
            const tab = event.target.closest('[role="tab"]');
            if (tab) selectTab(tab);
        });

        tabList.addEventListener('keydown', (event) => {
            const tab = event.target.closest('[role="tab"]');
            if (!tab) return;

            let nextTab;
            switch (event.key) {
                case 'ArrowLeft':
                    nextTab = tab.previousElementSibling || tabList.lastElementChild;
                    break;
                case 'ArrowRight':
                    nextTab = tab.nextElementSibling || tabList.firstElementChild;
                    break;
                case 'Home':
                    nextTab = tabList.firstElementChild;
                    break;
                case 'End':
                    nextTab = tabList.lastElementChild;
                    break;
                default:
                    return;
            }

            event.preventDefault();
            selectTab(nextTab);
            nextTab.focus();
        });
    })();
</script>
